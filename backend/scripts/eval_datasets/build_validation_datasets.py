GROUPS = {"loc": "定位资料(kb_0368jjmecb)", "mcx": "MCX-资料(kb_mvng8u1201)", "poc": "poc-资料(kb_3cm2gz6tyb)"}


def main() -> int:
    assert len(QUESTIONS) == 100, f"题目数应为 100，实际 {len(QUESTIONS)}"
    by_group: dict[str, list[dict]] = {g: [] for g in GROUPS}
    for index, section, group, query in QUESTIONS:
        by_group[group].append({"index": index, "section": section, "query": query})

    for group, items in by_group.items():
        items.sort(key=lambda it: it["index"])
        path = OUT_DIR / f"{group}.jsonl"
        with open(path, "w", encoding="utf-8") as f:
            for item in items:
                f.write(json.dumps(item, ensure_ascii=False) + "\n")
        print(f"{path.name:<12} n={len(items):>3}  {GROUPS[group]}")

    total = sum(len(v) for v in by_group.values())
    print(f"total={total}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
